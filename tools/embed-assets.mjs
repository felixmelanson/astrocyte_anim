// Inlines assets/*.png as data URIs into js/core/assets.js, so the canvas is never tainted when the page is opened
// from file:// (a tainted canvas cannot be exported by tools/render.mjs). Run after adding or changing an asset:
//   node tools/embed-assets.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(ROOT, 'assets');
const lines = fs.readdirSync(dir).filter(f => f.endsWith('.png')).sort()
  .map(f => `  ${JSON.stringify(path.basename(f, '.png'))}: 'data:image/png;base64,${fs.readFileSync(path.join(dir, f)).toString('base64')}',`);
fs.writeFileSync(path.join(ROOT, 'js', 'core', 'assets.js'),
`'use strict';
/* GENERATED by tools/embed-assets.mjs from assets/*.png: do not edit. IMG.<name> is an HTMLImageElement. */
const ASSET_SRC = {
${lines.join('\n')}
};
const IMG = {};
const IMG_READY = Promise.all(Object.entries(ASSET_SRC).map(([k, src]) => new Promise(res => { const im = new Image(); im.onload = im.onerror = res; im.src = src; IMG[k] = im; })));
`);
console.log('js/core/assets.js:', lines.length, 'asset(s)');
